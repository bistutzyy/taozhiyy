const { chromium } = require('playwright');
const sharp = require('sharp');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  fs.mkdirSync('.qa', { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:5196');
    await page.waitForFunction(() => document.documentElement.dataset.sceneReady === 'true');
    await page.waitForTimeout(2200);
    const debug = () => page.evaluate(() => window.__galleryDebug());
    let state = await debug();
    assert.equal(state.loaded, 6);
    assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).backgroundColor), 'rgb(8, 9, 14)', 'space uses a near-black surface');
    assert.equal(state.nodeCount, 6);
    await page.locator('#star-next').click();
    await page.waitForFunction(() => window.__galleryDebug().nodeCount === 3 && window.__galleryDebug().loaded === 3);
    assert.deepEqual((await debug()).projected.map(p=>p.id), ['qwen','designmd','drawio']);
    await page.waitForTimeout(1400);
    await page.screenshot({path:'.qa/second-field.png'});
    await page.locator('#star-prev').click();
    await page.waitForFunction(() => window.__galleryDebug().nodeCount === 6 && window.__galleryDebug().loaded === 6);
    await page.waitForTimeout(2200);
    state = await debug();
    const stillFrames = state.frameCount;
    await page.waitForTimeout(800);
    assert.ok((await debug()).frameCount - stillFrames < 3, 'idle canvas must stop rendering');
    const shot = await page.screenshot({ path: '.qa/desktop.png' });
    const stats = await sharp(shot).extract({ left: 280, top: 300, width: 900, height: 330 }).stats();
    assert.ok(stats.channels[0].stdev > 15, 'scene pixels must not be blank');
    const target = state.projected.find(p => p.id === 'reactbits');
    await page.mouse.click(target.x, target.y);
    await page.waitForTimeout(1400);
    assert.equal((await debug()).selected, 'reactbits');
    assert.ok((await debug()).zoom > 1.8, 'selecting a panel must move the camera closer');
    await page.screenshot({ path: '.qa/focused.png' });
    await page.locator('#open-project').click();
    assert.equal(await page.locator('#project-dialog').evaluate(el => el.open), true);
    assert.equal(await page.locator('#detail-title').textContent(), 'React Bits');
    await page.screenshot({ path: '.qa/detail.png' });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#project-dialog').evaluate(el => el.open), false);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'open-project');
    await page.locator('#next').click();
    assert.equal((await debug()).selected, 'gsap');
    await page.locator('#previous').click();
    assert.equal((await debug()).selected, 'reactbits');
    await page.locator('[data-project="ruic"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.project), 'ruic');
    assert.equal((await debug()).selected, 'ruic');
    await page.locator('#reset-camera').click();
    await page.waitForTimeout(1400);
    const beforeDrag = (await debug()).camera;
    await page.mouse.move(720, 530);
    await page.mouse.down();
    await page.mouse.move(800, 550, { steps: 10 });
    await page.mouse.up();
    await page.waitForTimeout(700);
    assert.notDeepEqual((await debug()).camera, beforeDrag);
    await page.locator('#orbit-toggle').click();
    const beforeOrbit = (await debug()).camera;
    await page.waitForTimeout(800);
    assert.notDeepEqual((await debug()).camera, beforeOrbit);
    await page.locator('#orbit-toggle').click();
    const beforeZoom = (await debug()).zoom;
    await page.locator('#zoom-in').click();
    assert.ok((await debug()).zoom > beforeZoom);
    await page.locator('#list-view').click();
    assert.equal(await page.locator('.project-card').count(), 9);
    assert.equal(await page.locator('[data-kind]').count(), 0);
    assert.ok(!/我的作品|精选分享|SELF-MADE|DISCOVERED/.test(await page.locator('body').innerText()));
    await page.locator('#project-search').fill('REACT BITS');
    assert.equal(await page.locator('.project-card').count(), 1);
    await page.locator('.project-card').click();
    assert.equal(await page.locator('#detail-title').textContent(), 'React Bits');
    await page.locator('#close-dialog').click();
    await page.locator('#project-search').fill('no-such-project');
    assert.equal(await page.locator('#empty-state').isVisible(), true);
    await page.locator('#clear-search').click();
    assert.equal(await page.locator('.project-card').count(), 9);
    for (const id of ['taozhiyy','ruic','shotcraft','reactbits','gsap','emil','qwen','designmd','drawio']) {
      await page.locator(`[data-detail="${id}"]`).click();
      assert.ok(await page.locator('.detail-section').count() >= 7);
      assert.ok((await page.locator('#detail-source').innerText()).includes('2026-10-28'));
      assert.equal(await page.locator('#project-dialog iframe').count(), 0);
      const links = await page.locator('#project-detail a[target="_blank"]').evaluateAll(nodes => nodes.map(a=>a.href));
      assert.ok(links.every(url => url.startsWith('https://')));
      if (id === 'ruic') {
        const video = page.locator('video');
        await video.evaluate(v => v.load());
        await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1, null, {timeout:25000});
        assert.ok(await video.evaluate(v => v.duration > 0));
        await page.screenshot({path:'.qa/ruic-detail.png'});
      }
      if (id === 'gsap') {
        await page.evaluate(() => { Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{window.__copied=text;}},configurable:true}); });
        await page.locator('[data-copy-section]').first().click();
        assert.ok((await page.evaluate(()=>window.__copied)).includes('npx skills add'));
        await page.screenshot({path:'.qa/tutorial.png'});
      }
      await page.locator('#close-dialog').click();
    }
    const cover = await page.locator('.card-cover').first().boundingBox();
    assert.ok(Math.abs(cover.width / cover.height - 1.6) < .02, 'covers preserve landscape ratio');
    await page.locator('#catalogue').evaluate(el => {el.scrollTop=0;});
    await page.screenshot({ path: '.qa/catalogue.png' });
    await page.locator('#scene-view').click();
    await page.locator('#reset-camera').click();
    await page.waitForTimeout(1400);
    for (const [width, height] of [[1920,1080],[768,1024],[390,844],[320,740]]) {
      await page.setViewportSize({ width, height });
      await page.locator('#reset-camera').click();
      await page.waitForTimeout(1400);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow ${width}`);
      const selection = await page.locator('.exhibit-selection').boundingBox();
      const footer = await page.locator('.exhibit-footer').boundingBox();
      assert.ok(selection.y + selection.height <= footer.y, `selection overlap ${width}`);
      await page.screenshot({ path: `.qa/scene-${width}.png` });
      await page.locator('#list-view').click();
      await page.waitForFunction(() => [...document.images].every(i => {
        const r = i.getBoundingClientRect();
        return !r.width || r.bottom < 0 || r.top > innerHeight || (i.complete && i.naturalWidth > 0);
      }));
      await page.screenshot({ path: `.qa/list-${width}.png` });
      await page.locator('#scene-view').click();
    }
    assert.deepEqual(errors, []);
    const reduced = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    await reduced.goto('http://127.0.0.1:5196');
    await reduced.waitForFunction(() => !!window.__galleryDebug);
    await reduced.locator('#orbit-toggle').click();
    assert.equal(await reduced.locator('#orbit-toggle').getAttribute('aria-pressed'), 'false');
    const fallback = await browser.newPage();
    await fallback.addInitScript(() => {
      const original = HTMLCanvasElement.prototype.getContext;
      HTMLCanvasElement.prototype.getContext = function (type, ...args) {
        if (type.startsWith('webgl')) return null;
        return original.call(this, type, ...args);
      };
    });
    await fallback.goto('http://127.0.0.1:5196');
    await fallback.waitForSelector('.list-mode');
    assert.equal(await fallback.locator('.project-card').count(), 9);
    const large = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    await large.route(/\/src\/catalog\.js(?:\?.*)?$/, async route => {
      const response = await route.fetch();
      await route.fulfill({response, body:(await response.text()) + '\nprojects.push(...Array.from({length:500-projects.length},(_,i)=>({...projects[i%projects.length],id:`extra-${i}`,title:`Scale Project ${i}`})));'});
    });
    await large.goto('http://127.0.0.1:5196');
    await large.waitForFunction(() => window.__galleryDebug?.().loaded === 6);
    assert.equal(await large.evaluate(() => window.__galleryDebug().visible.length), 500);
    assert.equal(await large.evaluate(() => window.__galleryDebug().nodeCount), 6);
    assert.equal(await large.locator('.dock-item').count(), 6);
    await large.locator('#star-next').click();
    await large.waitForFunction(() => window.__galleryDebug().selected === 'qwen');
    assert.equal(await large.evaluate(() => window.__galleryDebug().nodeCount), 6);
    await large.locator('#list-view').click();
    assert.equal(await large.locator('.project-card').count(), 12);
    await large.locator('#list-next').click();
    assert.equal(await large.locator('#list-pager span').textContent(), '02 / 42');
    await large.locator('#project-search').fill('Scale Project 490');
    assert.equal(await large.locator('.project-card').count(), 1);
    await large.locator('.project-card').click();
    assert.equal(await large.locator('#detail-title').textContent(), 'Scale Project 490');
    await large.locator('#close-dialog').click();
    await large.locator('#scene-view').click();
    assert.equal(await large.evaluate(() => { const s = window.__galleryDebug(); return s.projected.some(p => p.id === s.selected); }), true, 'returning from full-catalogue search keeps the selected project in the active star field');
    console.log('PASS: textures; pixels; idle; picking; camera; details; keyboard; filters; 5 viewports; reduced motion; WebGL fallback; 500-record catalogue with bounded scene nodes, pagination and search.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
